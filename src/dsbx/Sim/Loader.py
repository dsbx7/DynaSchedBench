"""Utilities for loading events and reconstructing InputModel from events.jsonl.

This module provides utilities to load scheduling instances directly from
events.jsonl files, which are generated by the `dsbx-gen gen` command. This is useful
for algorithms that want to solve instances without needing the original
configuration file.
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path
from typing import Any, Dict, List, Set, Tuple, Optional

from loguru import logger

from dsbx.Sim.Events import Event, ArrivalEvent, DueDateEvent
from dsbx.Gen import InputModel


def load_events_from_jsonl(events_file: Path) -> List[Event]:
    """Load all events from an events.jsonl file.
    
    Args:
        events_file: Path to events.jsonl file
        
    Returns:
        List of Event objects, sorted by time
    """
    from dsbx.Sim.Events import (
        ArrivalEvent, DueDateEvent, BreakdownEvent, PriorityChangeEvent,
        OrderCancellationEvent, MachineRepairCompletionEvent, ProcessTimeChangeEvent,
        PreventiveMaintenanceEvent, RouteChangeEvent, DueDateChangeEvent,
    )
    
    EVENT_TYPE_MAP = {
        "ARRIVAL": ArrivalEvent,
        "DUE_DATE_SET": DueDateEvent,
        "BREAKDOWN": BreakdownEvent,
        "PRIORITY_CHANGE": PriorityChangeEvent,
        "ORDER_CANCELLATION": OrderCancellationEvent,
        "REPAIR_COMPLETION": MachineRepairCompletionEvent,
        "PTIME_CHANGE": ProcessTimeChangeEvent,
        "PREVENTIVE_MAINTENANCE": PreventiveMaintenanceEvent,
        "ROUTE_CHANGE": RouteChangeEvent,
        "DUE_DATE_CHANGE": DueDateChangeEvent,
    }
    
    events: List[Event] = []
    
    with open(events_file, 'r', encoding='utf-8') as f:
        for line_num, line in enumerate(f, start=1):
            line = line.strip()
            if not line:
                continue
            
            try:
                event_dict = json.loads(line)
                event_type = event_dict.get("event_type")
                model_cls = EVENT_TYPE_MAP.get(event_type)
                
                if model_cls is None:
                    logger.warning(f"Unknown event type '{event_type}' at line {line_num}")
                    continue
                
                # Use Pydantic to parse and validate
                event = model_cls(**event_dict)
                events.append(event)
            except Exception as e:
                logger.warning(f"Failed to parse event at line {line_num}: {e}")
                continue
    
    # Sort by time
    events.sort(key=lambda e: e.time)
    
    logger.info(f"Loaded {len(events)} events from {events_file}")
    return events


def _infer_dynamic_scenarios_from_events(events: List[Event], n_jobs: int) -> Dict[str, Any]:
    """Infer a minimal dynamic_scenarios block from events.

    This is mainly to avoid strict validation errors that complain about
    emergency or cancellation events being present while the corresponding
    rates in dynamic_scenarios are zero.
    """

    arrival_jobs: Set[str] = set()
    emergency_jobs: Set[str] = set()
    cancel_events = 0

    for ev in events:
        et = getattr(ev, "event_type", None)
        if et == "ARRIVAL":
            jid = getattr(ev, "job_id", None)
            if isinstance(jid, str) and jid:
                arrival_jobs.add(jid)
                atype = getattr(ev, "arrival_type", None)
                if atype == "emergency":
                    emergency_jobs.add(jid)
        elif et == "ORDER_CANCELLATION":
            cancel_events += 1

    total_arrivals = len(arrival_jobs)
    emergency_ratio = 0.0
    if total_arrivals > 0 and emergency_jobs:
        emergency_ratio = float(len(emergency_jobs)) / float(total_arrivals)

    cancellation_rate = 0.0
    if n_jobs > 0 and cancel_events > 0:
        cancellation_rate = float(cancel_events) / float(n_jobs)

    dynamic_scenarios: Dict[str, Any] = {
        # Rates actually inferred from events
        "cancellation_rate": float(cancellation_rate),
        "emergency_job_ratio": float(emergency_ratio),

        # Other dynamic knobs are effectively "off" for JMS (probabilities=0),
        # but their parameter fields must still satisfy InputModel constraints.
        "priority_change_rate": 0.0,
        "emergency_priority": -1,
        "normal_priority_change_value": 0,
        "rework_probability": 0.0,
        "ptime_change_rate": 0.0,
        "ptime_change_multiplier": [1.0],

        # No preventive maintenance in JMS, keep interval 0 but ensure
        # pm_duration_mean > 0 to satisfy schema (value is unused when
        # pm_interval == 0).
        "pm_interval": 0.0,
        "pm_duration_mean": 1.0,
        "pm_duration_std": 0.0,

        # No batch arrivals in JMS, keep probability 0 but set
        # batch_size_mean >= 2 as required by the schema.
        "batch_arrival_probability": 0.0,
        "batch_size_mean": 2.0,
        "batch_size_std": 0.0,

        # No due-date change dynamics in JMS, probability 0 but require
        # due_date_change_factor > 0 by schema.
        "route_change_probability": 0.0,
        "due_date_change_probability": 0.0,
        "due_date_tightening_ratio": 0.0,
        "due_date_change_factor": 0.1,
    }

    return dynamic_scenarios


def infer_input_model_from_events(
    events: List[Event],
    horizon: Optional[float] = None,
    seed: int = 42,
) -> InputModel:
    """Infer an InputModel from a list of events.
    
    This reconstructs a minimal InputModel that can be used to create
    a simulation environment. The inferred model may not be identical
    to the original configuration, but it should be sufficient for
    running algorithms.
    
    Args:
        events: List of events loaded from events.jsonl
        horizon: Time horizon (if None, inferred from max due date)
        seed: Random seed for the model
        
    Returns:
        InputModel instance
    """
    # Collect information from events
    machine_groups: Set[str] = set()
    job_families: Dict[str, Set[tuple]] = defaultdict(set)  # family -> set of routes
    max_due_date = 0.0

    for event in events:
        if isinstance(event, ArrivalEvent):
            for group in event.routing:
                machine_groups.add(group)
            # Store route as tuple for hashing
            job_families[event.job_family].add(tuple(event.routing))
        elif isinstance(event, DueDateEvent):
            max_due_date = max(max_due_date, float(event.due_date))

    # Infer horizon
    if horizon is None:
        horizon = max(max_due_date * 1.5, 100.0)

    # Build machine configuration
    group_list = sorted(machine_groups)
    machines_config: List[Dict[str, Any]] = []
    for i, group in enumerate(group_list):
        machines_config.append(
            {
                "id": f"M{i+1}",
                "group": group,
                # Use default speed=1.0
            }
        )

    # Build process templates from observed job families and routes
    process_templates: List[Dict[str, Any]] = []
    family_list = sorted(job_families.keys())
    for family in family_list:
        routes = list(job_families[family])
        route_groups = list(routes[0]) if routes else []
        steps: List[Dict[str, Any]] = []
        for g in route_groups:
            steps.append(
                {
                    "machine_group": g,
                    # Minimal constant processing-time placeholder
                    "process_time": {
                        "dist": "const",
                        "mean": 1.0,
                        "scv": 0.0,
                    },
                }
            )
        if not steps and group_list:
            # Fallback: at least one dummy step to satisfy validators
            steps.append(
                {
                    "machine_group": group_list[0],
                    "process_time": {
                        "dist": "const",
                        "mean": 1.0,
                        "scv": 0.0,
                    },
                }
            )
        process_templates.append(
            {
                "family": family,
                "route": steps,
            }
        )

    # Job mix weights (equal weights)
    n_families = len(family_list)
    job_mix_weights = [1.0 / n_families] * n_families if n_families > 0 else [1.0]

    # Count jobs to estimate scale
    n_jobs = len([e for e in events if isinstance(e, ArrivalEvent)])

    # Infer dynamic_scenarios from events
    dynamic_scenarios = _infer_dynamic_scenarios_from_events(events, n_jobs)

    # Build minimal InputModel configuration compatible with v2.0 schema
    config: Dict[str, Any] = {
        "meta": {
            "seed": seed,
            "grid": 1,
            "version": "2.0",
        },
        "plant": {
            "machines": machines_config,
            "process_templates": process_templates,
            "job_mix_weights": job_mix_weights,
        },
        "scale": {
            "horizon": float(horizon),
            "jobs_total": int(n_jobs),
            "num_machines": len(machines_config),
            "num_job_families": max(len(process_templates), 1),
        },
        "dynamic_scenarios": dynamic_scenarios,
        "targets": {
            "rho_global": 0.8,
        },
        "outputs": {
            "path": "runs/inferred_from_events",
        },
    }

    # Create InputModel from dict
    try:
        model = InputModel.model_validate(config)
        num_machines = len(machines_config)
        num_groups = len({m["group"] for m in machines_config}) if machines_config else 0
        logger.info(
            f"Inferred InputModel from events: jobs_total={n_jobs}, "
            f"machines={num_machines}, groups={num_groups}, horizon={horizon}"
        )
        return model
    except Exception as e:
        logger.error(f"Failed to create InputModel from inferred config: {e}")
        raise


def infer_input_model_from_static_jobs(
    static_jobs_path: Path,
    events: List[Event],
    horizon: Optional[float] = None,
    seed: int = 42,
    static_machines_path: Optional[Path] = None,
) -> InputModel:
    """Infer an InputModel using static_jobs.json and events.

    This prefers the richer job-level static information (family, routing,
    process_times, due_date) exported by the generator, instead of
    reverse-engineering everything from events alone.
    """

    with open(static_jobs_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    jobs_dict: Dict[str, Any] = data.get("jobs", {}) or {}

    machine_groups: Set[str] = set()
    family_routes: Dict[str, Tuple[List[str], List[float]]] = {}
    max_due_date = 0.0

    for jid, info in jobs_dict.items():
        routing = [str(g) for g in info.get("routing", [])]
        pt = [float(x) for x in info.get("process_times", [])]
        family = info.get("job_family") or f"family_{jid}"

        for g in routing:
            machine_groups.add(g)

        if family not in family_routes and routing:
            family_routes[family] = (routing, pt)

        dd = info.get("due_date")
        if dd is not None:
            try:
                max_due_date = max(max_due_date, float(dd))
            except (TypeError, ValueError):
                continue

    if horizon is None:
        horizon = max(max_due_date * 1.5, 100.0) if max_due_date > 0 else 100.0

    group_list = sorted(machine_groups) or ["G1"]

    # Try to reconstruct the full machine list (including speeds) from
    # static_machines.json when available. This keeps dsbx-agent run-events aligned
    # with dsbx-agent run for instances generated via dsbx-gen gen.
    machines_config: List[Dict[str, Any]] = []
    if static_machines_path is not None and static_machines_path.exists():
        try:
            with open(static_machines_path, "r", encoding="utf-8") as fm:
                m_raw = json.load(fm)
            raw_list = m_raw.get("machines", []) or []
            for m in raw_list:
                if not isinstance(m, dict):
                    continue
                mid = str(m.get("id", "")).strip()
                grp = str(m.get("group", "")).strip()
                if not mid or not grp:
                    continue
                entry: Dict[str, Any] = {
                    "id": mid,
                    "group": grp,
                    "speed": float(m.get("speed", 1.0)),
                }
                machines_config.append(entry)

            known_groups = {m["group"] for m in machines_config}
            missing_groups = sorted(machine_groups - known_groups)
            if missing_groups:
                logger.warning(
                    "static_machines.json is missing groups referenced in static_jobs.json: {}",
                    ",".join(missing_groups),
                )
        except Exception as exc:
            logger.warning(
                "Failed to load static_machines.json from {} (falling back to group-based machines): {}",
                static_machines_path,
                exc,
            )
            machines_config = []

    if not machines_config:
        for i, group in enumerate(group_list):
            machines_config.append(
                {
                    "id": f"M{i+1}",
                    "group": group,
                }
            )

    process_templates: List[Dict[str, Any]] = []
    families = sorted(family_routes.keys())
    for family in families:
        routing, pt = family_routes[family]
        steps: List[Dict[str, Any]] = []
        for g, t in zip(routing, pt):
            steps.append(
                {
                    "machine_group": g,
                    "process_time": {
                        "dist": "const",
                        "mean": float(t),
                        "scv": 0.0,
                    },
                }
            )
        if not steps:
            steps.append(
                {
                    "machine_group": group_list[0],
                    "process_time": {
                        "dist": "const",
                        "mean": 1.0,
                        "scv": 0.0,
                    },
                }
            )
        process_templates.append({"family": family, "route": steps})

    if not process_templates:
        # Fallback: create a single dummy template
        process_templates.append(
            {
                "family": "default",
                "route": [
                    {
                        "machine_group": group_list[0],
                        "process_time": {
                            "dist": "const",
                            "mean": 1.0,
                            "scv": 0.0,
                        },
                    }
                ],
            }
        )

    n_families = len(process_templates)
    job_mix_weights = [1.0 / n_families] * n_families if n_families > 0 else [1.0]

    n_jobs = len([e for e in events if isinstance(e, ArrivalEvent)])

    # Infer dynamic_scenarios from events
    dynamic_scenarios = _infer_dynamic_scenarios_from_events(events, n_jobs)

    config: Dict[str, Any] = {
        "meta": {
            "seed": seed,
            "grid": 1,
            "version": "2.0",
        },
        "plant": {
            "machines": machines_config,
            "process_templates": process_templates,
            "job_mix_weights": job_mix_weights,
        },
        "scale": {
            "horizon": float(horizon),
            "jobs_total": int(n_jobs),
            "num_machines": len(machines_config),
            "num_job_families": max(len(process_templates), 1),
        },
        "dynamic_scenarios": dynamic_scenarios,
        "targets": {
            "rho_global": 0.8,
        },
        "outputs": {
            "path": "runs/inferred_from_events",
        },
    }

    try:
        model = InputModel.model_validate(config)
        num_machines = len(machines_config)
        num_groups = len({m["group"] for m in machines_config}) if machines_config else 0
        logger.info(
            f"Inferred InputModel from static_jobs: jobs_total={n_jobs}, "
            f"machines={num_machines}, groups={num_groups}, horizon={horizon}"
        )
        return model
    except Exception as e:
        logger.error(f"Failed to create InputModel from static_jobs: {e}")
        raise


def load_instance_from_events(
    events_file: Path,
    horizon: Optional[float] = None,
    seed: int = 42,
) -> Tuple[InputModel, List[Event]]:
    """Load a complete instance from an events.jsonl file.
    
    This is a convenience function that combines event loading and
    InputModel inference.
    
    Args:
        events_file: Path to events.jsonl file
        horizon: Time horizon (if None, inferred from events)
        seed: Random seed for the model
        
    Returns:
        Tuple of (InputModel, events list)
        
    Example:
        >>> model, events = load_instance_from_events("runs/my_instance/events.jsonl")
        >>> from dsbx.Sim import DynaSchedSim
        >>> sim = DynaSchedSim(model, events)
        >>> snapshot = sim.reset()
    """
    events = load_events_from_jsonl(events_file)

    input_model_path = events_file.parent / "input_model.json"
    if input_model_path.exists():
        try:
            raw = input_model_path.read_text(encoding="utf-8")
            model = InputModel.model_validate_json(raw)
            logger.info("Loaded InputModel from {}", input_model_path)
            return model, events
        except Exception as exc:
            logger.error("Failed to load InputModel from {}: {}", input_model_path, exc)

    # Prefer static_jobs.json (and, when available, static_machines.json) if
    # present in the same directory as events.jsonl.
    static_jobs_path = events_file.parent / "static_jobs.json"
    static_machines_path = events_file.parent / "static_machines.json"
    if static_jobs_path.exists():
        model = infer_input_model_from_static_jobs(
            static_jobs_path,
            events,
            horizon=horizon,
            seed=seed,
            static_machines_path=static_machines_path if static_machines_path.exists() else None,
        )
    else:
        model = infer_input_model_from_events(events, horizon=horizon, seed=seed)

    return model, events
