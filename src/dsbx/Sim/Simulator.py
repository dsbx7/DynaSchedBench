    def get_action_timing(self, action: Dict[str, Any]) -> Optional[Dict[str, float]]:
        """Return an estimated timing profile for ``action`` under the current state.

        The result is computed using the same instantaneous semantics as
        :meth:`estimate_action_score`, but instead of a scalar score it
        returns a dictionary with:

        - ``job_id``: job identifier (str)
        - ``op_index``: index of the operation being scheduled (int)
        - ``machine_id``: selected concrete machine id (str)
        - ``start_time``: earliest feasible start time given all constraints
        - ``end_time``: corresponding end time on the selected machine
        - ``proc_time_raw``: realized processing time before speed adjustment
        - ``machine_speed``: speed of the selected machine
        - ``proc_time_effective``: actual processing time on the machine

        The simulation state is not mutated.
        """

        try:
            job_id = str(action["job_id"])  # type: ignore[index]
            group = str(action.get("machine_group"))
            requested_mid = action.get("machine_id")
        except Exception:
            return None

        job = self.state.jobs.get(job_id)
        if job is None or job.current_op_index >= job.total_ops:
            return None

        k = job.current_op_index
        op = job.ops[k]

        machine_id = self._select_machine_for_action(job_id, group, requested_mid)
        mach = self.state.machines.get(machine_id)
        if mach is None:
            return None

        t_now = self.state.time
        job_avail = max(job.release_time, job.next_available_time)
        block_until = self._machine_block_until(machine_id, mach.group)
        start = max(t_now, job_avail, mach.available_from, block_until)

        # Mirror the non-overlap safeguard used in ``step_action`` so that
        # timing diagnostics are consistent with the actual scheduling
        # semantics: a new segment can never start before the latest
        # existing segment on the same machine.
        if mach.schedule_segments:
            latest_end = max(float(seg.end) for seg in mach.schedule_segments)
            if start < latest_end - 1e-9:
                start = latest_end

        raw_pt = float(op.proc_time_realized)
        speed = float(getattr(mach, "speed", 1.0))
        eff_pt = raw_pt / max(1e-9, speed)
        end = start + eff_pt

        return {
            "job_id": job_id,
            "op_index": float(k),
            "machine_id": machine_id,
            "start_time": float(start),
            "end_time": float(end),
            "proc_time_raw": float(raw_pt),
            "machine_speed": float(speed),
            "proc_time_effective": float(eff_pt),
        }

